        <h2>1. Droit de rétractation (14 jours)</h2>
        <p>Conformément aux dispositions de l'article L.221-18 du Code de la Consommation, vous disposez d'un délai de 14 jours à compter de la réception de vos produits pour exercer votre droit de rétractation sans avoir à justifier de motifs ni à payer de pénalité.</p>

        <h2>2. Conditions de retour</h2>
        <p>Pour que le retour soit accepté, les produits doivent être retournés dans leur état d'origine et complets (emballage, accessoires, notice...) permettant leur recommercialisation à l'état neuf. Les produits endommagés, salis ou incomplets ne seront pas repris.</p>

        <h2>3. Procédure de retour</h2>
        <ul>
            <li>Connectez-vous à votre compte client, rubrique "Mes commandes".</li>
            <li>Sélectionnez la commande concernée et cliquez sur "Demander un retour".</li>
            <li>Imprimez l'étiquette de retour qui vous sera envoyée par e-mail.</li>
            <li>Déposez votre colis dans le point relais le plus proche.</li>
        </ul>
        <p>Les frais de retour sont à la charge du client, sauf en cas d'erreur de notre part ou de produit défectueux.</p>

        <h2>4. Remboursement</h2>
        <p>En cas d'exercice du droit de rétractation, MaBoutique SAS procédera au remboursement des sommes versées dans un délai de 14 jours suivant la réception de votre colis retour, via le même moyen de paiement que celui utilisé lors de la commande.</p>
